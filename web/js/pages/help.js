export function helpHtml() {
  return `<div class="card noprint"><div class="tabs">${S.map(([id, t]) => `<a class="tab" href="#help-${id}" data-jump="${id}" style="text-decoration:none">${t}</a>`).join('')}</div></div>
    ${S.map(([id, t, body]) => `<section class="card help" id="help-${id}"><h2>${t}</h2>${body}</section>`).join('')}`;
}

export function bindJumps(root) {
  $$('[data-jump]', root).forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault();
    root.querySelector('#help-' + a.dataset.jump)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }));
}

export async function render(main) {
  main.innerHTML = pageHead('คู่มือการใช้งาน', 'ระบบคลังเครื่องมือแพทย์ บริษัท เมโทร เมดิคอล จำกัด', '<button class="b2" onclick="window.print()">พิมพ์คู่มือ</button>') + helpHtml();
  bindJumps(main);
}
